"""Check or emit the canonical Python 3.10 str.isdigit table used by kv-crypto.

Check: python3.10 fixtures/gen/generate_python_digits.py --check
Emit:  python3.10 fixtures/gen/generate_python_digits.py > crates/kv-crypto/src/python_digit_ranges.rs

The table deliberately targets CPython 3.10's Unicode 13.0.0 database. It is
not generated from Rust's broader, toolchain-dependent is_numeric property.
New Unicode digit additions require an explicit compatibility decision.
"""

import argparse
import pathlib
import platform
import sys
import unicodedata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the checked-in table")
    args = parser.parse_args()
    if (platform.python_implementation() != "CPython"
            or sys.version_info[:2] != (3, 10)
            or unicodedata.unidata_version != "13.0.0"):
        parser.error("requires canonical CPython 3.10 with Unicode 13.0.0")

    # Query CPython's actual predicate for every codepoint, rather than deriving
    # membership from a different Unicode property or hand-selecting scripts.
    ranges = []
    count = 0
    for point in range(sys.maxunicode + 1):
        if not chr(point).isdigit():
            continue
        count += 1
        if ranges and ranges[-1][1] + 1 == point:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])

    text = "\n".join([
        "// Generated by fixtures/gen/generate_python_digits.py; do not edit by hand.",
        "// Source: CPython 3.10 str.isdigit(), Unicode 13.0.0.",
        f"// Exhaustive enumeration: {count} codepoints in {len(ranges)} inclusive ranges.",
        "const DIGIT_RANGES: &[(u32, u32)] = &[",
        *[f"    (0x{start:04X}, 0x{end:04X})," for start, end in ranges],
        "];",
        "",
    ])
    if args.check:
        path = pathlib.Path(__file__).resolve().parents[2] / "crates/kv-crypto/src/python_digit_ranges.rs"
        if path.read_text(encoding="utf-8") != text:
            raise SystemExit("Python digit table differs; regenerate with canonical Python 3.10")
        print(f"Python digit table verified: {count} codepoints, {len(ranges)} ranges (Unicode 13.0.0)")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
